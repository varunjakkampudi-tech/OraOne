"""Server-generated secrets for channel bindings (SDK signing, Telegram webhook).

Secrets are generated by the server, shown to the user once, and stored only as
Fernet ciphertext (``app.core.crypto``) plus a four-character hint for display.
Stored keys are ``<name>_encrypted`` and ``<name>_hint`` inside
``AgentChannel.configuration``. The legacy plaintext ``<name>`` key is still read
so bindings written before this module keep working.
"""

from __future__ import annotations

import secrets
from typing import Any, Optional

from app.core import crypto

# Channel key -> name of the per-binding secret it carries.
SECRET_NAME_BY_CHANNEL: dict[str, str] = {
    "sdk": "sdk_secret",
    "telegram": "telegram_webhook_secret",
}

# Non-secret binding settings that may be returned to the client.
PUBLIC_CONFIG_KEYS: tuple[str, ...] = (
    "phone_number_id",
    "instagram_account_id",
    "inbound_address",
)

_MASK_PREFIX = "••••"  # four bullet characters


def generate_secret() -> str:
    """A URL-safe random secret of 43 characters (256 bits)."""
    return secrets.token_urlsafe(32)


def with_secret(
    configuration: Optional[dict[str, Any]], name: str, secret: str
) -> dict[str, Any]:
    """A copy of ``configuration`` with ``secret`` stored encrypted under ``name``.

    Any legacy plaintext copy under ``name`` is removed.
    """
    config = dict(configuration or {})
    config.pop(name, None)
    config[f"{name}_encrypted"] = crypto.encrypt(secret)
    config[f"{name}_hint"] = secret[-4:]
    return config


def read_secret(configuration: Optional[dict[str, Any]], name: str) -> Optional[str]:
    """The usable plaintext secret for ``name``, or None when none is stored."""
    config = configuration or {}
    encrypted = config.get(f"{name}_encrypted")
    if encrypted:
        return crypto.decrypt(encrypted)
    legacy = config.get(name)
    return legacy or None


def has_secret(configuration: Optional[dict[str, Any]], name: str) -> bool:
    config = configuration or {}
    return bool(config.get(f"{name}_encrypted") or config.get(name))


def masked_secrets(configuration: Optional[dict[str, Any]]) -> dict[str, str]:
    """Display-only forms of each stored secret, e.g. ``"••••a1b2"``. Never the value."""
    config = configuration or {}
    out: dict[str, str] = {}
    for name in SECRET_NAME_BY_CHANNEL.values():
        if has_secret(config, name):
            hint = str(config.get(f"{name}_hint") or "")
            out[name] = f"{_MASK_PREFIX}{hint}" if hint else _MASK_PREFIX
    return out


def public_settings(configuration: Optional[dict[str, Any]]) -> dict[str, str]:
    """Only the non-secret settings. Ciphertext, hints and legacy secrets are dropped."""
    config = configuration or {}
    return {
        key: str(config[key])
        for key in PUBLIC_CONFIG_KEYS
        if config.get(key) not in (None, "")
    }
